from docx import Document
from docx.shared import Pt, RGBColor, Cm

doc = Document()

for section in doc.sections:
    section.top_margin = Cm(1.5)
    section.bottom_margin = Cm(1.5)
    section.left_margin = Cm(2.0)
    section.right_margin = Cm(2.0)

def add_slide_title(doc, num, title):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(18)
    p.paragraph_format.space_after = Pt(4)
    run = p.add_run(f"【슬라이드 {num}】 {title}")
    run.bold = True
    run.font.size = Pt(14)
    run.font.color.rgb = RGBColor(0x1F, 0x49, 0x7D)
    p2 = doc.add_paragraph("─" * 55)
    p2.paragraph_format.space_before = Pt(0)
    p2.paragraph_format.space_after = Pt(6)
    p2.runs[0].font.size = Pt(9)
    p2.runs[0].font.color.rgb = RGBColor(0x99, 0x99, 0x99)

def add_body(doc, lines):
    for line in lines:
        if line == "":
            doc.add_paragraph("")
            continue
        indent = 0
        text = line
        if line.startswith("    •"):
            indent = 2
            text = line.strip()
        elif line.startswith("  •"):
            indent = 1
            text = line.strip()
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(indent * 0.5)
        p.paragraph_format.space_before = Pt(1)
        p.paragraph_format.space_after = Pt(2)
        p.add_run(text).font.size = Pt(10.5)

